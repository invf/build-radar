function initials(name: string) {
  return name
    .split(/[\s\-\/()«»"']+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((w) => w[0])
    .join('')
    .toUpperCase()
    .slice(0, 2)
}

function useCopyPrompt() {
  const [copied, setCopied] = useState<string | null>(null)
  const copy = (text: string) => {
    navigator.clipboard.writeText(text).then(() => {
      setCopied(text)
      setTimeout(() => setCopied(null), 2000)
    })
  }
  return { copy, copied }
}

// ─── Overrides (localStorage) ─────────────────────────────────────────────────

const LS_KEY = 'br-contact-overrides'

interface Override {
  pri: Priority
  note: string
  description?: string
  website?: string
  address?: string
  phone?: string
  email?: string
  procurement?: string
  funding?: string
  projectsText?: string
}

function getEffective(contact: Contact, ov?: Override) {
  return {
    pri:         ov?.pri         ?? contact.pri,
    note:        ov?.note        ?? contact.note,
    description: ov?.description ?? contact.details.description,
    website:     ov?.website     ?? contact.details.website     ?? '',
    address:     ov?.address     ?? contact.details.address     ?? '',
    phone:       ov?.phone       ?? contact.details.phone       ?? '',
    email:       ov?.email       ?? contact.details.email       ?? '',
    procurement: ov?.procurement ?? contact.details.procurement ?? '',
    funding:     ov?.funding     ?? contact.details.funding     ?? '',
    projects:    ov?.projectsText != null
      ? ov.projectsText.split('\n').filter(Boolean)
      : (contact.details.projects ?? []),
    projectsText: ov?.projectsText ?? (contact.details.projects ?? []).join('\n'),
  }
}

function useOverrides() {
  const [overrides, setOverrides] = useState<Record<string, Override>>({})

  useEffect(() => {
    try {
      const raw = localStorage.getItem(LS_KEY)
      if (raw) setOverrides(JSON.parse(raw))
    } catch { /* ignore */ }
  }, [])

  const save = (name: string, o: Override) => {
    setOverrides((prev) => {
      const next = { ...prev, [name]: o }
      localStorage.setItem(LS_KEY, JSON.stringify(next))
      return next
    })
  }

  return { overrides, save }
}

// ─── Custom contacts (localStorage) ──────────────────────────────────────────

const CUSTOM_LS_KEY = 'br-custom-contacts'

function useCustomContacts() {
  const [customContacts, setCustomContacts] = useState<Contact[]>([])

  useEffect(() => {
    try {
      const raw = localStorage.getItem(CUSTOM_LS_KEY)
      if (raw) setCustomContacts(JSON.parse(raw))
    } catch { /* ignore */ }
  }, [])

  const add = (c: Contact) => {
    setCustomContacts((prev) => {
      const next = [...prev, c]
      localStorage.setItem(CUSTOM_LS_KEY, JSON.stringify(next))
      return next
    })
  }

  const remove = (name: string) => {
    setCustomContacts((prev) => {
      const next = prev.filter((c) => c.name !== name)
      localStorage.setItem(CUSTOM_LS_KEY, JSON.stringify(next))
      return next
    })
  }

  return { customContacts, add, remove }
}

// ─── Hidden contacts (localStorage) ──────────────────────────────────────────

const HIDDEN_LS_KEY = 'br-hidden-contacts'

function useHiddenContacts() {
  const [hiddenNames, setHiddenNames] = useState<Set<string>>(new Set())

  useEffect(() => {
    try {
      const raw = localStorage.getItem(HIDDEN_LS_KEY)
      if (raw) setHiddenNames(new Set(JSON.parse(raw) as string[]))
    } catch { /* ignore */ }
  }, [])

  const hide = (name: string) => {
    setHiddenNames((prev) => {
      const next = new Set([...prev, name])
      localStorage.setItem(HIDDEN_LS_KEY, JSON.stringify([...next]))
      return next
    })
  }

  const restoreAll = () => {
    setHiddenNames(new Set())
    localStorage.removeItem(HIDDEN_LS_KEY)
  }

  return { hiddenNames, hide, restoreAll }
}

