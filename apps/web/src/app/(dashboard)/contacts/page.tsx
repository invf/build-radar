// ─── Contacts Tab ─────────────────────────────────────────────────────────────

function ContactsTab({ onOpen, onEdit, overrides, customContacts, onDelete, hiddenNames, onRestoreAll }: {
  onOpen: (c: Contact) => void
  onEdit: (c: Contact) => void
  overrides: Record<string, Override>
  customContacts: Contact[]
  onDelete: (name: string) => void
  hiddenNames: Set<string>
  onRestoreAll: () => void
}) {
  const [query, setQuery] = useState('')
  const [segFilter, setSegFilter] = useState<Segment | ''>('')
  const [priFilter, setPriFilter] = useState<string>('')

  const allContacts = [...CONTACTS, ...customContacts].filter((c) => !hiddenNames.has(c.name))

  const filtered = allContacts.filter((c) => {
    const pri = overrides[c.name]?.pri ?? c.pri
    if (segFilter && c.seg !== segFilter) return false
    if (priFilter && pri !== parseInt(priFilter)) return false
    if (query) {
      const q = query.toLowerCase()
      if (!c.name.toLowerCase().includes(q) && !c.role.toLowerCase().includes(q) && !c.tags.join(' ').toLowerCase().includes(q)) return false
    }
    return true
  })

  const grouped = filtered.reduce<Record<Segment, Contact[]>>((acc, c) => {
    if (!acc[c.seg]) acc[c.seg] = []
    acc[c.seg].push(c)
    return acc
  }, {} as Record<Segment, Contact[]>)

  return (
    <div className="space-y-5">
      <div className="grid grid-cols-2 sm:grid-cols-4 gap-3">
        {[
          { n: filtered.length, label: 'Всього контактів' },
          { n: filtered.filter((c) => c.pri === 3).length, label: 'Гарячих (пріоритет)' },
          { n: filtered.filter((c) => c.pri === 2).length, label: 'Теплих' },
          { n: Object.keys(grouped).length, label: 'Сегменти' },
        ].map(({ n, label }) => (
          <div key={label} className="rounded-xl border border-zinc-800 bg-zinc-900/50 px-4 py-3">
            <div className="text-2xl font-semibold text-zinc-100">{n}</div>
            <div className="text-[11px] text-zinc-500 mt-0.5">{label}</div>
          </div>
        ))}
      </div>

      {hiddenNames.size > 0 && (
        <div className="flex items-center justify-between px-4 py-2.5 rounded-lg border border-zinc-700/50 bg-zinc-900/30">
          <span className="text-xs text-zinc-500 flex items-center gap-1.5">
            <Trash2 className="h-3 w-3 text-zinc-600" />
            {hiddenNames.size} прихованих контактів
          </span>
          <button
            onClick={onRestoreAll}
            className="text-xs text-brand-400 hover:text-brand-300 font-medium transition-colors"
          >
            Відновити всі
          </button>
        </div>
      )}

      <div className="flex flex-wrap gap-2">
        <div className="relative flex-1 min-w-[180px]">
          <Search className="absolute left-3 top-1/2 -translate-y-1/2 h-3.5 w-3.5 text-zinc-500" />
          <Input className="pl-8 h-9 bg-zinc-900 border-zinc-700 text-sm" placeholder="Пошук компанії, ролі, тегу..." value={query} onChange={(e) => setQuery(e.target.value)} />
        </div>
        <select value={segFilter} onChange={(e) => setSegFilter(e.target.value as Segment | '')} className="h-9 rounded-md border border-zinc-700 bg-zinc-900 text-zinc-300 text-sm px-3 min-w-[150px] cursor-pointer">
          <option value="">Всі сегменти</option>
          <option value="dev">Девелопери</option>
          <option value="proj">Проектні орг.</option>
          <option value="inst">Інституційні</option>
          <option value="bank">Банки / IFI</option>
          <option value="heat">Теплопостачання</option>
          <option value="water">Водоканали</option>
        </select>
        <select value={priFilter} onChange={(e) => setPriFilter(e.target.value)} className="h-9 rounded-md border border-zinc-700 bg-zinc-900 text-zinc-300 text-sm px-3 min-w-[130px] cursor-pointer">
          <option value="">Всі пріоритети</option>
          <option value="3">Гарячі</option>
          <option value="2">Теплі</option>
          <option value="1">Холодні</option>
        </select>
      </div>

      {(Object.entries(grouped) as [Segment, Contact[]][]).map(([seg, contacts]) => (
        <div key={seg}>
          <p className="text-[11px] font-semibold uppercase tracking-wider text-zinc-500 mb-3">{SEG_LABELS[seg]} ({contacts.length})</p>
          <div className="grid grid-cols-1 sm:grid-cols-2 xl:grid-cols-3 gap-3">
            {contacts.map((c) => (
              <ContactCard key={c.name} contact={c} override={overrides[c.name]} onOpen={onOpen} onEdit={onEdit} onDelete={onDelete} />
            ))}
          </div>
        </div>
      ))}

      {filtered.length === 0 && (
        <div className="text-center py-16 text-zinc-500 text-sm">Нічого не знайдено</div>
      )}
    </div>
  )
}

